// Guide: launch a runner pool from the matrix.
const { open, close, BASE } = require('./rec');
(async () => {
  const r = await open('launch');
  const { page, click, type, caption, wait, scrollTo, moveTo, shot } = r;
  await page.goto(BASE + '/', { waitUntil: 'networkidle' });
  await page.click('[data-tab="tab-sizing"]');
  await page.click('#sidebar-toggle-btn');
  await scrollTo('#qualification-table-body', 'start');
  await page.evaluate(() => window.scrollBy({ top: -140 }));
  await wait(600);
  await moveTo(900, 420, 1);
  await caption('1. In the matrix, click Launch on the host you want', 1200);
  await click("#qualification-table-body tr:first-child button[onclick^='launchQualRow(']", 900);
  await page.waitForSelector('#rp-dialog[open]');
  await caption('The dialog starts with the row\'s machine, zone, and runner size', 2000);
  await shot('launch-a-pool', 'launch-dialog', '#rp-dialog', 0);
  await caption('2. Pick where the runners register: an organization or one repository');
  await click('#rp-target', 300);
  await page.keyboard.press('Escape');
  await wait(1200);
  await caption('3. Spin-down is on: the pool runs no hosts until a job asks for them');
  const auto = await page.locator('#rp-auto').boundingBox();
  await moveTo(auto.x + 8, auto.y + 8);
  await wait(2200);
  await caption('4. Add a label so only your jobs land on these runners');
  await type('#rp-labels', 'small', 120);
  await wait(500);
  await page.locator('#rp-check').scrollIntoViewIfNeeded();
  await caption('5. Check the summary: what it costs idle and with every host busy', 2600);
  await shot('launch-a-pool', 'launch-summary', '#rp-check', 10);
  await caption('6. Click Launch');
  await click('#rp-submit', 1000);
  await page.waitForSelector('#rp-done:not([hidden])', { timeout: 10000 });
  await caption('The dialog shows the runs-on line for your workflows', 2200);
  await shot('launch-a-pool', 'launch-done', '#rp-dialog', 0);
  await click('#rp-done-close', 700);
  await scrollTo('#rp-panel', 'start');
  await caption('The pool is in the Runner pools panel, spun down until a job is queued', 2600);
  await shot('launch-a-pool', 'pool-row', '#rp-panel', 4);
  await caption('', 300);
  console.log(await close(r, 'launch-a-pool'));
})();
