// Guide: review instances and what they cost.
const { open, close, BASE } = require('./rec');
const { withFleet } = require('./demo-fleet');
(async () => {
  const r = await open('instances', { transform(p, j, req) { return p === '/api/overview' ? withFleet(j, req) : j; } });
  const { page, click, type, caption, wait, moveTo, shot, scrollTo } = r;
  await page.goto(BASE + '/', { waitUntil: 'networkidle' });
  r.frames.length = 0;
  await moveTo(140, 300, 1);
  await caption('1. Open VM Instances & Cost', 900);
  await click('[data-tab="tab-instances"]', 700);
  await page.click('#sidebar-toggle-btn');
  await wait(500);
  await scrollTo('#tab-instances', 'start');
  await page.evaluate(() => window.scrollBy({ top: -110 }));
  await caption('Every host, running or deleted, with what it cost in the window', 2400);
  await shot('review-instances-and-cost', 'instances-table');
  await caption('2. Change the time window. Costs update to match');
  await click("button[onclick='applyHoursWindow(168)'], button[onclick=\"applyHoursWindow(168)\"]", 1300);
  await caption('3. Narrow the list by role');
  await page.selectOption('#inst-role-filter', { index: 2 });
  await wait(1700);
  await page.selectOption('#inst-role-filter', { index: 0 });
  await caption('4. Search by name, region, or machine type');
  await type('#inst-search-input', 'n4a', 160);
  await wait(1700);
  await shot('review-instances-and-cost', 'instances-search');
  await page.locator('#inst-search-input').fill('');
  await page.locator('#inst-search-input').dispatchEvent('input');
  await wait(400);
  await caption('5. Click a column header to sort by it');
  const hdr = page.locator('table:has(#instances-table-body) thead th', { hasText: /Total/ }).first();
  await click(hdr, 1500);
  await click(hdr, 1500);
  await caption('6. Clear Include deleted to see only what runs now');
  await click('#inst-include-deleted', 2000);
  await shot('review-instances-and-cost', 'instances-running');
  await caption('', 300);
  console.log(await close(r, 'review-instances-and-cost'));
})();
